        public static string Get(string key)
        {
            var culture = Thread.CurrentThread.CurrentUICulture.Name;
            
            if (!Resources.ContainsKey(culture))
            {
                culture = "tr-TR"; // Default
            }

            if (Resources[culture].ContainsKey(key))
            {
                return Resources[culture][key];
            }
            
            // Fallback to Turkish if key not found
            if (Resources["tr-TR"].ContainsKey(key))
            {
                return Resources["tr-TR"][key];
            }

            return key;
        }
